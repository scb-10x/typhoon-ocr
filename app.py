import base64
from io import BytesIO
import os
from openai import OpenAI
from dotenv import load_dotenv
from typhoon_ocr import prepare_ocr_messages, normalize_thai_text
from typhoon_ocr.ocr_utils import _extract_natural_text_json
import gradio as gr
from PIL import Image

load_dotenv()

openai = OpenAI(base_url=os.getenv("TYPHOON_BASE_URL"), api_key=os.getenv("TYPHOON_API_KEY"))

theme = gr.themes.Soft(
    primary_hue=gr.themes.Color(
        c50="#f7f7fd",
        c100="#dfdef8",
        c200="#c4c1f2",
        c300="#a29eea",
        c400="#8f8ae6",
        c500="#756fe0",
        c600="#635cc1",
        c700="#4f4a9b",
        c800="#433f83",
        c900="#302d5e",
        c950="#302d5e",
    ),
    secondary_hue="rose",
    neutral_hue="stone",
)


def process_pdf(pdf_or_image_file, task_type, page_number):
    if pdf_or_image_file is None:
        return None, "No file uploaded"

    orig_filename = pdf_or_image_file.name

    try:
        messages = prepare_ocr_messages(
            pdf_or_image_path=orig_filename,
            task_type=task_type,
            target_image_dim=1800,
            target_text_length=8000,
            page_num=page_number if page_number else 1,
        )

        # Extract the image from the message content for display
        image_url = messages[0]["content"][1]["image_url"]["url"]
        image_base64 = image_url.replace("data:image/png;base64,", "")
        image_pil = Image.open(BytesIO(base64.b64decode(image_base64)))

        # Send messages to OpenAI compatible API
        response = openai.chat.completions.create(
            model=os.getenv("TYPHOON_OCR_MODEL", "typhoon-ocr"),
            messages=messages,
            max_tokens=16384,
            extra_body={
                "repetition_penalty": 1.1 if task_type == "v1.5" else 1.2,
                "temperature": 0.1,
                "top_p": 0.6,
            },
        )
        text_output = response.choices[0].message.content

        if task_type == "v1.5":
            markdown_out = normalize_thai_text(text_output).replace("<figure>", "").replace("</figure>", "")
        else:
            try:
                natural_text = _extract_natural_text_json(text_output)
                markdown_out = normalize_thai_text(natural_text).replace("<figure>", "").replace("</figure>", "")
            except Exception as e:
                markdown_out = f"⚠️ Could not extract `natural_text` from output.\nError: {str(e)}"

        return image_pil, markdown_out

    except Exception as e:
        return None, f"Error processing file: {str(e)}"


